"""CLI configuration (``~/.routes/config.toml``) and engine connection settings.

Secrets are not stored in config.toml. The engine token is read from the
Compose env file the engine was started with (``engine.env_file``).
"""

from __future__ import annotations

import secrets
import tomllib
from dataclasses import asdict, dataclass, field
from pathlib import Path

import tomli_w

from routes_storage.paths import RoutesHome, restrict

DEFAULT_ENGINE_PORT = 8190


@dataclass
class EngineConfig:
    compose_file: str = ""
    env_file: str = ""
    url: str = f"http://127.0.0.1:{DEFAULT_ENGINE_PORT}"


@dataclass
class UiConfig:
    reduced_motion: bool = False
    animations: bool = True


@dataclass
class Config:
    engine: EngineConfig = field(default_factory=EngineConfig)
    ui: UiConfig = field(default_factory=UiConfig)
    current_project: str = ""
    report_format: str = "markdown"

    @classmethod
    def load(cls, home: RoutesHome) -> "Config":
        if not home.config.exists():
            return cls()
        data = tomllib.loads(home.config.read_text(encoding="utf-8"))
        engine = {k: v for k, v in (data.get("engine") or {}).items() if k in EngineConfig.__dataclass_fields__}
        ui = {k: v for k, v in (data.get("ui") or {}).items() if k in UiConfig.__dataclass_fields__}
        cfg = cls(engine=EngineConfig(**engine), ui=UiConfig(**ui))
        cfg.current_project = str(data.get("current_project") or "")
        fmt = str(data.get("report_format") or "markdown")
        cfg.report_format = fmt if fmt in ("markdown", "html", "json") else "markdown"
        return cfg

    def save(self, home: RoutesHome) -> None:
        home.config.write_text(tomli_w.dumps(asdict(self)), encoding="utf-8")
        restrict(home.config, 0o600)


def read_env_file(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def generate_engine_env(path: Path) -> None:
    """Write a Compose env file with fresh random secrets (never overwrites)."""
    if path.exists():
        return
    lines = [
        "# Generated by `routes init`. Secrets for the local ROUTES engine. Do not commit or share.",
        f"SANDBOX_MANAGER_TOKEN={secrets.token_urlsafe(32)}",
        f"GATEWAY_CONTROL_TOKEN={secrets.token_urlsafe(32)}",
        f"ROUTES_ENGINE_PORT={DEFAULT_ENGINE_PORT}",
        "GATEWAY_DEV_ALLOW_HOSTS=",
        "# Used only by the legacy web profile (docker compose --profile web).",
        "POSTGRES_USER=routes",
        f"POSTGRES_PASSWORD={secrets.token_urlsafe(24)}",
        "POSTGRES_DB=routes",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    restrict(path, 0o600)


@dataclass(frozen=True)
class EngineSettings:
    url: str
    token: str
    compose_file: Path | None
    env_file: Path | None
    dev_allow_hosts: str


def engine_settings(cfg: Config) -> EngineSettings:
    env_file = Path(cfg.engine.env_file) if cfg.engine.env_file else None
    env = read_env_file(env_file) if env_file else {}
    url = cfg.engine.url
    port = env.get("ROUTES_ENGINE_PORT")
    if port and port.isdigit() and url == EngineConfig().url:
        url = f"http://127.0.0.1:{int(port)}"
    return EngineSettings(url=url, token=env.get("SANDBOX_MANAGER_TOKEN", ""),
                          compose_file=Path(cfg.engine.compose_file) if cfg.engine.compose_file else None,
                          env_file=env_file, dev_allow_hosts=env.get("GATEWAY_DEV_ALLOW_HOSTS", ""))
